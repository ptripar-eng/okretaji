#!/usr/bin/env python3
"""Keep Okretaji's homepage editorial list aligned with published Croatian articles.

Reads the repository sitemap and published HR HTML files only. Drafts and other
unpublished files are not included. Existing hand-curated article cards remain
untouched; missing published articles are added to an auto-generated block.
Run --check in CI to reject stale archives.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
INDEX = ROOT / "index.html"
SITEMAP = ROOT / "sitemap.xml"

STATIC_PAGES = {
    "f1.html", "motogp.html", "tehnicki-vodici.html", "usporedbe.html",
    "o-nama.html", "kontakt.html", "privatnost.html", "index.html",
    "svi-clanci.html",
}

BEGIN = "/* BEGIN AUTO_EDITORIAL: generated by scripts/sync_editorial_index.py */"
END = "/* END AUTO_EDITORIAL */"
SEARCH_MARKER = "/* Search every editorial article, including items outside the homepage selection. */"
HREF = re.compile(r"""(?:\bhref\s*:\s*|["']href["']\s*:\s*)["']([^"']+\.html)["']""")


class ArticleMetadata(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.in_title = False
        self.title_parts: list[str] = []
        self.meta: dict[str, str] = {}

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attributes = dict(attrs)
        if tag == "title":
            self.in_title = True
        elif tag == "meta":
            key = (attributes.get("name") or attributes.get("property") or "").lower()
            value = attributes.get("content") or ""
            if key and value:
                self.meta[key] = value

    def handle_endtag(self, tag: str) -> None:
        if tag == "title":
            self.in_title = False

    def handle_data(self, data: str) -> None:
        if self.in_title:
            self.title_parts.append(data)


def published_articles() -> list[str]:
    root = ET.parse(SITEMAP).getroot()
    urls = []
    for node in root.iter():
        if not node.tag.endswith("loc") or not node.text:
            continue
        parsed = urlsplit(node.text.strip())
        path = parsed.path.lstrip("/")
        if parsed.hostname != "okretaji.com" or "/" in path:
            continue
        if not path.endswith(".html") or path in STATIC_PAGES:
            continue
        urls.append(path)
    if len(urls) != len(set(urls)):
        raise ValueError("Duplicate Croatian article URLs in sitemap.xml")
    return sorted(urls)


def curated_hrefs(source: str) -> set[str]:
    found: set[str] = set()
    for array_name in ("EDITORIAL", "SEARCH_EXTRA"):
        start = source.find("const " + array_name + " = [")
        if start < 0:
            raise ValueError(f"Missing {array_name} array in index.html")
        end = source.find("\n];", start)
        if end < 0:
            raise ValueError(f"Malformed {array_name} array in index.html")
        found.update(HREF.findall(source[start:end]))
    return found


def article_data(path: str) -> dict[str, object]:
    file = ROOT / path
    if not file.is_file():
        raise ValueError(f"Sitemap lists missing article: {path}")
    parser = ArticleMetadata()
    parser.feed(file.read_text(encoding="utf-8"))
    title = "".join(parser.title_parts).strip()
    title = re.sub(r"\s*[|–-]\s*Okretaji\s*$", "", title, flags=re.I)
    description = parser.meta.get("description", "").strip()
    if not title or not description:
        raise ValueError(f"Published article missing title/description: {path}")
    category = (
        "FORMULA 1" if path.startswith(("f1-", "kimi-antonelli")) or
        "formula-1" in path or "bolida" in path
        else "MOTOGP" if path.startswith(("motogp-", "marc-marquez", "stoner-"))
        else "TEHNIKA / AUTOMOBILI" if "turba" in path
        else "OKRETAJI"
    )
    obj: dict[str, object] = {
        "t": title, "s": description, "href": path, "tag": category
    }
    when = parser.meta.get("article:published_time") or parser.meta.get("date")
    if when and re.match(r"^\d{4}-\d{2}-\d{2}", when):
        obj["published"] = when
    picture = parser.meta.get("og:image")
    if picture and (picture.startswith("https://") or picture.startswith("/")):
        obj["images"] = [{"src": picture, "alt": "Ilustracija uz članak"}]
    return obj


def transform(source: str) -> tuple[str, list[str]]:
    manually_listed = curated_hrefs(source)
    missing = [p for p in published_articles() if p not in manually_listed]
    records = sorted((article_data(path) for path in missing),
                     key=lambda row: str(row.get("published", "")), reverse=True)
    payload = ",\n".join(
        "  " + json.dumps(row, ensure_ascii=False, separators=(",", ":"))
        .replace("<", r"\u003c")
        for row in records
    )
    block = (
        BEGIN + "\nconst AUTO_EDITORIAL = [\n" + payload +
        "\n];\nconst STORIES = [...EDITORIAL, ...AUTO_EDITORIAL];\n" +
        END
    )
    if BEGIN in source:
        if source.count(BEGIN) != 1 or source.count(END) != 1:
            raise ValueError("Malformed generated section markers")
        left = source.index(BEGIN)
        right = source.index(END, left) + len(END)
        source = source[:left] + block + source[right:]
    else:
        if source.count(SEARCH_MARKER) != 1:
            raise ValueError("Cannot locate editorial index insertion point")
        source = source.replace(SEARCH_MARKER, block + "\n\n" + SEARCH_MARKER)

    source = source.replace("[...EDITORIAL,...SEARCH_EXTRA]", "[...STORIES,...SEARCH_EXTRA]")
    source = source.replace("Promise.all(EDITORIAL.map(", "Promise.all(STORIES.map(")
    source = source.replace("new Map(EDITORIAL.map(", "new Map(STORIES.map(")
    if source.count("const STORIES = [...EDITORIAL, ...AUTO_EDITORIAL];") != 1:
        raise ValueError("Generated STORIES array is missing or duplicated")
    return source, missing


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    original = INDEX.read_text(encoding="utf-8")
    changed, missing = transform(original)
    print(f"Published sitemap articles: {len(published_articles())}; "
          f"automatically indexed (outside curated list): {len(missing)}")
    for path in missing:
        print("  + " + path)
    if changed != original:
        if args.check:
            sys.exit("Article archive is stale; run scripts/sync_editorial_index.py")
        INDEX.write_text(changed, encoding="utf-8")
        print("Updated index.html")
    else:
        print("Homepage archive is up to date")


if __name__ == "__main__":
    main()
